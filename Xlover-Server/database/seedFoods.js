  for (const [name, key, cat, met, icon] of EXERCISES) {
    const r = stmtEx.run(name, key, cat, met, icon, name);
    if (r.changes > 0) inserted.exercises++;
  }

  const stmtRw = db.prepare(`
    INSERT INTO rewards (creator_id, name, description, points_cost, icon, is_active)
    SELECT 1, ?, ?, ?, ?, 1
    WHERE NOT EXISTS (SELECT 1 FROM rewards WHERE name = ?)
  `);
  for (const [name, desc, cost, icon] of REWARDS) {
    const r = stmtRw.run(name, desc, cost, icon, name);
    if (r.changes > 0) inserted.rewards++;
  }
